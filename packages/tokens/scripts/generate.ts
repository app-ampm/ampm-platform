/**
 * The generator behind `pnpm tokens:build` (scripts/build.ts writes what this returns):
 *   tailwind.preset.cjs   the Tailwind preset both apps load (`presets: [preset]`)
 *   tailwind.preset.d.cts its type
 *   tokens.css            the CSS variables for light and dark, for contexts without Tailwind
 *
 * Colours become CSS variables holding RGB channels (`--color-brand: 122 31 79`) and the preset maps
 * them as `rgb(var(--color-brand) / <alpha-value>)`, so `bg-brand/50` works and dark mode is a
 * variable swap: `:root` holds the light values, `.dark:root` the dark ones (darkMode "class";
 * `.dark:root` is the selector NativeWind's compiler recognises for class dark mode).
 */
import { breakpoints } from "../src/breakpoints.ts";
import { colors, statusColors, surfaceColors, textColors } from "../src/colors.ts";
import { layers } from "../src/layers.ts";
import { duration, easing } from "../src/motion.ts";
import { radii } from "../src/radii.ts";
import { shadows } from "../src/shadows.ts";
import { sizes, spacing } from "../src/spacing.ts";
import { fontFamily, fontSize, fontWeight } from "../src/typography.ts";
import { channels, contrast } from "./contrast.ts";

export const LIGHT_ROOT_SELECTOR = ":root";
export const DARK_ROOT_SELECTOR = ".dark:root";
export const MIN_TEXT_CONTRAST = 4.5;

type Scheme = "light" | "dark";

export interface Outputs {
  readonly preset: string;
  readonly types: string;
  readonly css: string;
}

/** Every text colour on every surface of its scheme, every status on its soft background, brand-ink on brand. */
export function contrastFailures(): string[] {
  const failures: string[] = [];
  for (const scheme of ["light", "dark"] as const) {
    for (const text of textColors) {
      for (const surface of surfaceColors) {
        const ratio = contrast(colors[text][scheme], colors[surface][scheme]);
        if (ratio < MIN_TEXT_CONTRAST)
          failures.push(`${scheme}: ${text} on ${surface} is ${ratio.toFixed(2)}:1`);
      }
    }
    for (const status of statusColors) {
      const ratio = contrast(colors[status][scheme], colors[`${status}-soft`][scheme]);
      if (ratio < MIN_TEXT_CONTRAST)
        failures.push(`${scheme}: ${status} on ${status}-soft is ${ratio.toFixed(2)}:1`);
    }
    const ink = contrast(colors["brand-ink"][scheme], colors.brand[scheme]);
    if (ink < MIN_TEXT_CONTRAST)
      failures.push(`${scheme}: brand-ink on brand is ${ink.toFixed(2)}:1`);
  }
  return failures;
}

export function checkContrast(): void {
  const failures = contrastFailures();
  if (failures.length > 0) {
    throw new Error(
      `tokens: text colours below ${MIN_TEXT_CONTRAST}:1 (WCAG AA)\n  ${failures.join("\n  ")}`,
    );
  }
}

function colorVariables(scheme: Scheme): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, token] of Object.entries(colors)) {
    out[`--color-${name}`] = channels(token[scheme]).join(" ");
  }
  return out;
}

function fontVariables(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, stack] of Object.entries(fontFamily)) {
    out[`--font-${name}`] = stack.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  }
  return out;
}

function presetColors(): Record<string, string> {
  const out: Record<string, string> = {
    transparent: "transparent",
    current: "currentColor",
    inherit: "inherit",
  };
  for (const name of Object.keys(colors)) {
    out[name] = `rgb(var(--color-${name}) / <alpha-value>)`;
  }
  return out;
}

function screens(): Record<string, string> {
  return Object.fromEntries(Object.entries(breakpoints).map(([name, px]) => [name, `${px}px`]));
}

const header =
  "/* Generated by `pnpm tokens:build` from packages/tokens/src. Do not edit; change the tokens and rebuild. */";

function presetSource(): string {
  const theme = {
    colors: presetColors(),
    spacing,
    borderRadius: radii,
    fontFamily,
    fontSize,
    fontWeight,
    boxShadow: shadows,
    screens: screens(),
    zIndex: layers,
    transitionDuration: duration,
    transitionTimingFunction: easing,
    extend: { height: sizes, minHeight: sizes, width: sizes, minWidth: sizes },
  };
  const variables = {
    [LIGHT_ROOT_SELECTOR]: colorVariables("light"),
    [DARK_ROOT_SELECTOR]: colorVariables("dark"),
  };
  return [
    header,
    '"use strict";',
    'const plugin = require("tailwindcss/plugin");',
    "",
    "/** CSS variables for the two schemes; the light values on :root, the dark ones when `dark` is on the root. */",
    `const variables = ${JSON.stringify(variables, null, 2)};`,
    "",
    '/** @type {import("tailwindcss").Config} */',
    "module.exports = {",
    '  darkMode: "class",',
    `  theme: ${JSON.stringify(theme, null, 2).replace(/\n/g, "\n  ")},`,
    "  plugins: [plugin(({ addBase }) => addBase(variables))],",
    "};",
    "",
  ].join("\n");
}

function presetTypes(): string {
  return [
    header,
    'import type { Config } from "tailwindcss";',
    "declare const preset: Config;",
    "export = preset;",
    "",
  ].join("\n");
}

function cssSource(): string {
  const block = (selector: string, vars: Record<string, string>) =>
    `${selector} {\n${Object.entries(vars)
      .map(([k, v]) => `  ${k}: ${v};`)
      .join("\n")}\n}`;
  const light = { ...colorVariables("light"), ...fontVariables() };
  return [
    header,
    block(LIGHT_ROOT_SELECTOR, light),
    block(DARK_ROOT_SELECTOR, colorVariables("dark")),
    "",
  ].join("\n\n");
}

/** Checks the contrast gate, then returns the three files' contents. */
export function generate(): Outputs {
  checkContrast();
  return { preset: presetSource(), types: presetTypes(), css: cssSource() };
}
