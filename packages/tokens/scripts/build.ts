/**
 * tokens:build — generates, from ../src:
 *   dist/tailwind.preset.cjs   the Tailwind preset both apps load (`presets: [preset]`)
 *   dist/tailwind.preset.d.cts its type
 *   dist/tokens.css            the CSS variables for light and dark, for contexts without Tailwind
 *
 * Runs on Node's built-in type stripping (`node scripts/build.ts`, Node 24), so this file uses only
 * erasable TypeScript and imports its sources with explicit `.ts` extensions.
 *
 * Colours become CSS variables holding RGB channels (`--color-brand: 122 31 79`) and the preset maps
 * them as `rgb(var(--color-brand) / <alpha-value>)`, so `bg-brand/50` works and dark mode is a
 * variable swap: `:root` holds the light values, `.dark:root` the dark ones (darkMode "class").
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { breakpoints } from "../src/breakpoints.ts";
import { colors, statusColors, surfaceColors, textColors, type Hex } from "../src/colors.ts";
import { layers } from "../src/layers.ts";
import { duration, easing } from "../src/motion.ts";
import { radii } from "../src/radii.ts";
import { shadows } from "../src/shadows.ts";
import { sizes, spacing } from "../src/spacing.ts";
import { fontFamily, fontSize, fontWeight } from "../src/typography.ts";

const LIGHT_ROOT_SELECTOR = ":root";
const DARK_ROOT_SELECTOR = ".dark:root";
const MIN_TEXT_CONTRAST = 4.5;

type Scheme = "light" | "dark";

// ---------------------------------------------------------------------------------------------
// Colour maths (WCAG 2.x relative luminance and contrast ratio)

function channels(hex: Hex): [number, number, number] {
  const value = hex.slice(1);
  if (!/^[0-9a-f]{6}$/i.test(value)) throw new Error(`tokens: ${hex} is not a 6-digit hex colour`);
  return [0, 2, 4].map((i) => Number.parseInt(value.slice(i, i + 2), 16)) as [number, number, number];
}

function luminance(hex: Hex): number {
  const [r, g, b] = channels(hex).map((c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  }) as [number, number, number];
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a: Hex, b: Hex): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

function checkContrast(): void {
  const failures: string[] = [];
  for (const scheme of ["light", "dark"] as const) {
    for (const text of textColors) {
      for (const surface of surfaceColors) {
        const ratio = contrast(colors[text][scheme], colors[surface][scheme]);
        if (ratio < MIN_TEXT_CONTRAST) failures.push(`${scheme}: ${text} on ${surface} is ${ratio.toFixed(2)}:1`);
      }
    }
    for (const status of statusColors) {
      const ratio = contrast(colors[status][scheme], colors[`${status}-soft`][scheme]);
      if (ratio < MIN_TEXT_CONTRAST) failures.push(`${scheme}: ${status} on ${status}-soft is ${ratio.toFixed(2)}:1`);
    }
    const ink = contrast(colors["brand-ink"][scheme], colors.brand[scheme]);
    if (ink < MIN_TEXT_CONTRAST) failures.push(`${scheme}: brand-ink on brand is ${ink.toFixed(2)}:1`);
  }
  if (failures.length > 0) {
    throw new Error(`tokens: text colours below ${MIN_TEXT_CONTRAST}:1 (WCAG AA)\n  ${failures.join("\n  ")}`);
  }
}

// ---------------------------------------------------------------------------------------------
// Outputs

function colorVariables(scheme: Scheme): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, token] of Object.entries(colors)) {
    out[`--color-${name}`] = channels(token[scheme]).join(" ");
  }
  return out;
}

function fontVariables(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, stack] of Object.entries(fontFamily)) {
    out[`--font-${name}`] = stack.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  }
  return out;
}

function presetColors(): Record<string, string> {
  const out: Record<string, string> = { transparent: "transparent", current: "currentColor", inherit: "inherit" };
  for (const name of Object.keys(colors)) {
    out[name] = `rgb(var(--color-${name}) / <alpha-value>)`;
  }
  return out;
}

function screens(): Record<string, string> {
  return Object.fromEntries(Object.entries(breakpoints).map(([name, px]) => [name, `${px}px`]));
}

const header = "/* Generated by `pnpm tokens:build` from packages/tokens/src. Do not edit; change the tokens and rebuild. */";

function presetSource(): string {
  const theme = {
    colors: presetColors(),
    spacing,
    borderRadius: radii,
    fontFamily,
    fontSize,
    fontWeight,
    boxShadow: shadows,
    screens: screens(),
    zIndex: layers,
    transitionDuration: duration,
    transitionTimingFunction: easing,
    extend: {
      height: sizes,
      minHeight: sizes,
      width: sizes,
      minWidth: sizes,
    },
  };
  const variables = {
    [LIGHT_ROOT_SELECTOR]: colorVariables("light"),
    [DARK_ROOT_SELECTOR]: colorVariables("dark"),
  };
  return [
    header,
    '"use strict";',
    'const plugin = require("tailwindcss/plugin");',
    "",
    "/** CSS variables for the two schemes; the light values on :root, the dark ones when `dark` is on the root. */",
    `const variables = ${JSON.stringify(variables, null, 2)};`,
    "",
    '/** @type {import("tailwindcss").Config} */',
    "module.exports = {",
    '  darkMode: "class",',
    `  theme: ${JSON.stringify(theme, null, 2).replace(/\n/g, "\n  ")},`,
    "  plugins: [plugin(({ addBase }) => addBase(variables))],",
    "};",
    "",
  ].join("\n");
}

function presetTypes(): string {
  return [header, 'import type { Config } from "tailwindcss";', "declare const preset: Config;", "export = preset;", ""].join("\n");
}

function cssSource(): string {
  const block = (selector: string, vars: Record<string, string>) =>
    `${selector} {\n${Object.entries(vars)
      .map(([k, v]) => `  ${k}: ${v};`)
      .join("\n")}\n}`;
  const light = { ...colorVariables("light"), ...fontVariables() };
  const dark = colorVariables("dark");
  return [header, block(LIGHT_ROOT_SELECTOR, light), block(DARK_ROOT_SELECTOR, dark), ""].join("\n\n");
}

// ---------------------------------------------------------------------------------------------

checkContrast();

const dist = join(dirname(fileURLToPath(import.meta.url)), "..", "dist");
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, "tailwind.preset.cjs"), presetSource());
writeFileSync(join(dist, "tailwind.preset.d.cts"), presetTypes());
writeFileSync(join(dist, "tokens.css"), cssSource());
console.log(`tokens: wrote tailwind.preset.cjs, tailwind.preset.d.cts and tokens.css to ${dist}`);
